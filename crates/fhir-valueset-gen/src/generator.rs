/// Escape arbitrary text so it can be emitted safely inside generated Rust
/// string literals.
fn escape_str(s: &str) -> String {
    // Normalize CRLF/CR to LF to avoid emitting bare '\r' into generated Rust sources.
    let normalized = s.replace("\r\n", "\n").replace('\r', "\n");

    // Escape for a standard Rust string literal (handles \n, \t, \", \\ and control chars).
    normalized
        .chars()
        .flat_map(|c| c.escape_default())
        .collect()
}

/// Convert a raw concept code into a Rust enum variant name suitable for
/// generated CodeSystem enums.
fn code_to_variant(code: &str) -> String {
    // Convert code strings like "amended" or "asked-unknown" or "1.2.3" into Rust identifiers.
    let mut out = String::new();
    let mut capitalize = true;
    for ch in code.chars() {
        if ch.is_ascii_alphanumeric() {
            if out.is_empty() && ch.is_ascii_digit() {
                out.push('_');
            }
            if capitalize {
                out.push(ch.to_ascii_uppercase());
                capitalize = false;
            } else {
                out.push(ch);
            }
        } else {
            capitalize = true;
        }
    }
    if out.is_empty() {
        out.push_str("Code");
    }

    // If the variant ended up as `Code_<digits>` (e.g., for purely numeric codes),
    // make it `Code<digits>` to satisfy Rust style lints.
    if let Some(rest) = out.strip_prefix("Code_") {
        if !rest.is_empty() && rest.chars().all(|c| c.is_ascii_digit()) {
            out = format!("Code{}", rest);
        }
    }

    // Avoid Rust keywords (common minimal set; add more if needed)
    match out.as_str() {
        "Self" | "Super" | "Crate" | "Type" | "Mod" | "Move" | "Ref" | "Box" | "Loop" | "Match"
        | "Where" | "As" | "In" | "Fn" | "Gen" => {
            out.push('_');
        }
        _ => {}
    }

    out
}
