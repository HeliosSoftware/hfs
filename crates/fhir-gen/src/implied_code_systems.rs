//! Generates the implied-code-system tables under
//! `crates/fhir/src/implied_code_systems/{ver}.rs` (#1395).
//!
//! A `code` element carries no system of its own: FHIR says its system is
//! implied by the element's binding. For a token search parameter whose every
//! path is a `code` element with a *required* binding to a ValueSet drawn from
//! a single CodeSystem, that CodeSystem is the only system a `system|code`
//! search on it can name and still match. The table records exactly those
//! parameters — anything less certain (extensible or example bindings, a
//! ValueSet spanning several systems or importing another ValueSet, a
//! FHIRPath expression that is more than a plain dotted path, a choice or
//! `contentReference` leaf) is left out, and keeps matching any system.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fs::File;
use std::io::{self, BufReader, Write};
use std::path::Path;

use serde_json::Value;

/// `(resource type, search parameter code) → (expression, implied system)`.
type Table = BTreeMap<(String, String), (String, String)>;

/// Writes `<output_root>/implied_code_systems/{ver}.rs` from the spec bundles
/// in `version_dir`.
pub(crate) fn generate_implied_code_systems_file(
    output_root: &Path,
    version_dir: &Path,
    version_name: &str,
) -> io::Result<()> {
    let table = build_table(version_dir)?;

    let dir = output_root.join("implied_code_systems");
    std::fs::create_dir_all(&dir)?;
    let path = dir.join(format!("{}.rs", version_name.to_lowercase()));
    let mut file = File::create(&path)?;

    writeln!(
        file,
        "//! Implied code systems of `code`-typed token search parameters, FHIR {version_name}."
    )?;
    writeln!(file, "//!")?;
    writeln!(
        file,
        "//! Generated by `cargo run -p helios-fhir-gen -- --all` (or `--compartments-only`)"
    )?;
    writeln!(
        file,
        "//! from `crates/fhir-gen/resources/{version_name}/`: `search-parameters.json`,"
    )?;
    writeln!(
        file,
        "//! `profiles-resources.json`, `profiles-types.json` and `valuesets.json`. Do not"
    )?;
    writeln!(file, "//! edit by hand — re-run the generator instead.")?;
    writeln!(file)?;
    writeln!(
        file,
        "/// The `(expression, system)` of `code` on `resource_type`, when every path of"
    )?;
    writeln!(
        file,
        "/// `expression` that applies to `resource_type` is a `code` element with a"
    )?;
    writeln!(
        file,
        "/// required binding to a ValueSet drawn from the single CodeSystem `system`."
    )?;
    writeln!(file, "pub fn implied_code_system(")?;
    writeln!(file, "    resource_type: &str,")?;
    writeln!(file, "    code: &str,")?;
    writeln!(file, ") -> Option<(&'static str, &'static str)> {{")?;
    writeln!(file, "    match (resource_type, code) {{")?;
    for ((resource_type, code), (expression, system)) in &table {
        writeln!(
            file,
            "        ({resource_type:?}, {code:?}) => Some(({expression:?}, {system:?})),"
        )?;
    }
    writeln!(file, "        _ => None,")?;
    writeln!(file, "    }}")?;
    writeln!(file, "}}")?;

    Ok(())
}

fn build_table(version_dir: &Path) -> io::Result<Table> {
    let mut structures: HashMap<String, HashMap<String, Value>> = HashMap::new();
    for name in ["profiles-resources.json", "profiles-types.json"] {
        for resource in bundle_resources(&version_dir.join(name))? {
            if resource["resourceType"] != "StructureDefinition"
                || resource["derivation"] != "specialization"
            {
                continue;
            }
            let (Some(ty), Some(elements)) = (
                resource["type"].as_str(),
                resource["snapshot"]["element"].as_array(),
            ) else {
                continue;
            };
            let by_path = elements
                .iter()
                .filter_map(|e| Some((e["path"].as_str()?.to_string(), e.clone())))
                .collect();
            structures.insert(ty.to_string(), by_path);
        }
    }

    let mut value_sets: HashMap<String, Value> = HashMap::new();
    for resource in bundle_resources(&version_dir.join("valuesets.json"))? {
        if resource["resourceType"] == "ValueSet" {
            if let Some(url) = resource["url"].as_str() {
                value_sets.insert(url.to_string(), resource.clone());
            }
        }
    }

    let resolver = Resolver {
        structures,
        value_sets,
    };
    let mut table = Table::new();
    for resource in bundle_resources(&version_dir.join("search-parameters.json"))? {
        if resource["resourceType"] != "SearchParameter" || resource["type"] != "token" {
            continue;
        }
        let (Some(code), Some(expression), Some(bases)) = (
            resource["code"].as_str(),
            resource["expression"].as_str(),
            resource["base"].as_array(),
        ) else {
            continue;
        };
        let paths: Vec<&str> = expression.split('|').map(str::trim).collect();
        // Anything but a union of plain dotted paths (`.where(…)`, `as`,
        // `ofType(…)`, `resolve()`) is left out, whichever base it targets.
        if !paths.iter().all(|p| is_plain_path(p)) {
            continue;
        }
        for base in bases.iter().filter_map(Value::as_str) {
            let prefix = format!("{base}.");
            let systems: BTreeSet<Option<String>> = paths
                .iter()
                .filter(|p| p.starts_with(&prefix))
                .map(|p| resolver.implied_system(p))
                .collect();
            if systems.len() != 1 {
                continue;
            }
            if let Some(Some(system)) = systems.into_iter().next() {
                table.insert(
                    (base.to_string(), code.to_string()),
                    (expression.to_string(), system),
                );
            }
        }
    }
    Ok(table)
}

struct Resolver {
    /// Type name → element path → snapshot ElementDefinition.
    structures: HashMap<String, HashMap<String, Value>>,
    /// Canonical URL → ValueSet.
    value_sets: HashMap<String, Value>,
}

impl Resolver {
    /// The implied system of the `code` element at `path`, walking into
    /// backbone elements, `contentReference`s and complex datatypes.
    fn implied_system(&self, path: &str) -> Option<String> {
        let mut segments = path.split('.');
        let root = segments.next()?;
        let mut elements = self.structures.get(root)?;
        let mut prefix = root.to_string();
        let segments: Vec<&str> = segments.collect();
        for (i, segment) in segments.iter().enumerate() {
            let element_path = format!("{prefix}.{segment}");
            let element = elements.get(&element_path)?;
            let last = i + 1 == segments.len();
            if let Some(reference) = element["contentReference"].as_str() {
                if last {
                    return None;
                }
                prefix = reference.rsplit('#').next()?.to_string();
                continue;
            }
            let types = element["type"].as_array()?;
            let [ty] = types.as_slice() else {
                return None;
            };
            let ty = ty["code"].as_str()?;
            if last {
                if ty != "code" {
                    return None;
                }
                let binding = &element["binding"];
                if binding["strength"] != "required" {
                    return None;
                }
                return self.single_system(binding["valueSet"].as_str()?);
            }
            if ty == "BackboneElement" || ty == "Element" {
                prefix = element_path;
            } else {
                elements = self.structures.get(ty)?;
                prefix = ty.to_string();
            }
        }
        None
    }

    /// The one CodeSystem `value_set` draws from, if it draws from exactly one
    /// and imports no other ValueSet.
    fn single_system(&self, value_set: &str) -> Option<String> {
        let url = value_set.split('|').next()?;
        let includes = self.value_sets.get(url)?["compose"]["include"].as_array()?;
        let mut systems = BTreeSet::new();
        for include in includes {
            if include.get("valueSet").is_some() {
                return None;
            }
            systems.insert(include["system"].as_str()?);
        }
        let mut systems = systems.into_iter();
        match (systems.next(), systems.next()) {
            (Some(system), None) => Some(system.to_string()),
            _ => None,
        }
    }
}

/// `Type.element(.element)*`, nothing else.
fn is_plain_path(path: &str) -> bool {
    let mut parts = path.split('.');
    let root_ok = parts
        .next()
        .is_some_and(|p| p.starts_with(|c: char| c.is_ascii_uppercase()) && is_identifier(p));
    let mut rest = parts.peekable();
    root_ok && rest.peek().is_some() && rest.all(is_identifier)
}

fn is_identifier(s: &str) -> bool {
    s.starts_with(|c: char| c.is_ascii_alphabetic()) && s.chars().all(|c| c.is_ascii_alphanumeric())
}

fn bundle_resources(path: &Path) -> io::Result<Vec<Value>> {
    let file = File::open(path)?;
    let bundle: Value = serde_json::from_reader(BufReader::new(file))?;
    Ok(bundle["entry"]
        .as_array()
        .map(|entries| entries.iter().map(|e| e["resource"].clone()).collect())
        .unwrap_or_default())
}
