//! Implied code systems of `code`-typed token search parameters (#1395).
//!
//! A `code` element carries no system: FHIR says it is implied by the
//! element's binding. These tables record the search parameters for which that
//! implied system is unambiguous — every path the parameter's expression takes
//! on the resource type is a `code` element with a required binding to a
//! ValueSet drawn from one CodeSystem (`Patient.gender` →
//! `http://hl7.org/fhir/administrative-gender`). A `system|code` search on such
//! a parameter can only match when it names that system.
//!
//! Submodules are generated by `cargo run -p helios-fhir-gen -- --all` (or
//! `--compartments-only`); do not edit them by hand.

#[cfg(feature = "R4")]
pub mod r4;
#[cfg(feature = "R4B")]
pub mod r4b;
#[cfg(feature = "R5")]
pub mod r5;
#[cfg(feature = "R6")]
pub mod r6;

/// The implied system of search parameter `code` on `resource_type`, when its
/// FHIRPath `expression` is the spec's and the spec gives it one.
///
/// The expression must match the generated table's exactly, so a custom
/// SearchParameter that reuses a spec code for another path gets `None`.
///
/// Every compiled-in FHIR version is consulted, since the caller (a search
/// parameter registry) does not know which one it serves. Where two versions
/// bind the same expression to different systems (`MedicationRequest.intent`
/// is `medicationrequest-intent` in R4, `request-intent` in R5), the answer is
/// ambiguous and is `None`.
pub fn implied_code_system(
    resource_type: &str,
    code: &str,
    expression: &str,
) -> Option<&'static str> {
    let candidates = [
        #[cfg(feature = "R4")]
        r4::implied_code_system(resource_type, code),
        #[cfg(feature = "R4B")]
        r4b::implied_code_system(resource_type, code),
        #[cfg(feature = "R5")]
        r5::implied_code_system(resource_type, code),
        #[cfg(feature = "R6")]
        r6::implied_code_system(resource_type, code),
    ];
    let mut systems = candidates
        .into_iter()
        .flatten()
        .filter(|(table_expression, _)| *table_expression == expression)
        .map(|(_, system)| system);
    let system = systems.next()?;
    systems.all(|other| other == system).then_some(system)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gender_is_administrative_gender() {
        assert_eq!(
            implied_code_system(
                "Patient",
                "gender",
                "Patient.gender | Person.gender | Practitioner.gender | RelatedPerson.gender",
            ),
            Some("http://hl7.org/fhir/administrative-gender")
        );
    }

    #[test]
    fn another_expression_has_none() {
        assert_eq!(
            implied_code_system("Patient", "gender", "Patient.extension.value"),
            None
        );
    }

    #[test]
    fn a_coding_parameter_has_none() {
        assert_eq!(
            implied_code_system("Observation", "code", "Observation.code"),
            None
        );
    }
}
